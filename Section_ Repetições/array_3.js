const frutas = ["Morango", "Laranja", "Tomate", "Limão"];

//adciona ao fim da lista
frutas.push("Kiwi");
console.log(frutas);

//adcionar no inicio da lista
frutas.unshift("Melancia")
console.log(frutas)

//para apagar o ultimo elemento do array
frutas.pop();
console.log(frutas)

//para apagar o primeiro elemento do array
frutas.shift();
console.log(frutas)